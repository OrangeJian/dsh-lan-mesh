import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {MeshNode} from '../lib/service.mjs';
import {MeshServer} from '../lib/transport.mjs';
import {emptyState,createRoom,joinRoom} from '../lib/rooms.mjs';
import {normalizeContent} from '../lib/shared-doc-state.mjs';

test('non-Leader human writes through real signed Leader RPC and retains revision history',async t=>{
 const home=await mkdtemp(join(tmpdir(),'shared-doc-integration-')),previous=process.env.DSH_HOME;
 process.env.DSH_HOME=home;
 const state=emptyState();
 const room=createRoom(state,{name:'Docs',leader:{nodeId:'node-b',sessionId:'human',name:'B'}},()=> 'aaaaaaaaaaaa11112222333344444444');
 joinRoom(state,room.id,{nodeId:'node-a',sessionId:'human',name:'A'});
 joinRoom(state,room.id,{nodeId:'node-a',sessionId:'agent',name:'Agent'});
 joinRoom(state,room.id,{nodeId:'node-b',sessionId:'worker',name:'Worker'});
 const nodes=['a','b'].map((id,index)=>{const node=new MeshNode({config:{port:39861+index,clusterSecret:'secret',trustedPeers:[],autoWake:false}});node.started=true;node.identity={nodeId:`node-${id}`,name:id};node.roomsDoc=structuredClone(state);return node;});
 const [a,b]=nodes;
 t.after(async()=>{for(const node of nodes)await node.close();if(previous===undefined)delete process.env.DSH_HOME;else process.env.DSH_HOME=previous;await rm(home,{recursive:true,force:true});});
 const leader=await b.sharedDocumentService();
 b.server=new MeshServer({describe:()=>b.describe(),secret:()=> 'secret',trustedPeers:()=>[],onSharedDoc:e=>leader.receive(e),onMessage:e=>b.receive(e)});await b.server.listen(0);
 a.resolvePeers=()=>[{nodeId:'node-b',address:'127.0.0.1',httpPort:b.server.port}];
 const created=await a.documentOperation('createDocument',{roomId:room.id,title:'Design',content:'one\ntwo\n',via:'panel'});
 const documentId=created.document.documentId;
 const read=await a.documentOperation('getDocument',{documentId,via:'panel'});
 assert.equal(read.document.content,normalizeContent('one\ntwo\n'));
 const baseRevisionId=read.document.headRevisionId;
 const edited=await a.documentOperation('submitDocumentProposal',{documentId,baseRevisionId,content:'ONE\ntwo\n',message:'clarify',proposalId:'prop-aaaaaaaaaaaa',via:'panel'});
 assert.equal(edited.status,'clean');
 const history=await a.documentOperation('listDocumentHistory',{documentId,via:'panel'});
 assert.equal(history.revisions.length,2);
 assert.equal(history.revisions[0].authorName,'a','relay preserves the original author display name');
 assert.equal((await a.documentOperation('getDocument',{documentId,revisionId:baseRevisionId,via:'panel'})).document.content,normalizeContent('one\ntwo\n'));
 const follower=await a.sharedDocumentService();
 assert.equal(follower.store.state().documents[documentId].contentHash,leader.store.state().documents[documentId].contentHash);
 await assert.rejects(a.documentOperation('getDocument',{documentId,via:'tool',sessionId:'node-b/human'}),/session|Agent|actor/i);
 const prompts=[];
 Object.defineProperty(a,'agents',{value:{get:id=>id==='agent'?{id,followup:prompt=>prompts.push(prompt)}:undefined,list:()=>[{id:'agent'}]}});
 a.config.autoWake=true;
 const contextMessage={room:room.id,sessionId:'human',text:'Review the pinned design',messageId:'context-stable',mentions:[{memberKey:'node-a/agent',label:'Agent'}],contextSelection:{selectedDocumentVersions:[{documentId,revisionId:baseRevisionId,contentHash:read.document.contentHash}]}};
 await a.sayInRoom(contextMessage);
 await a.sayInRoom(contextMessage);
 assert.equal(prompts.length,1);
 assert.equal(a.roomDetail({room:room.id,sessionId:'human'}).messages.filter(message=>message.id==='context-stable').length,1);
 assert.match(prompts[0].content[0].text,/one\\ntwo/);
 const audits=await a.contextDeliveryStore().list();
 assert.equal(audits.length,1);
 assert.equal(audits[0].status,'delivered');
 assert.equal(audits[0].packet.selectedDocumentVersions[0].revisionId,baseRevisionId);
 assert.equal(audits[0].packet.selectedDocumentVersions[0].content,normalizeContent('one\ntwo\n'));
 const mergedRequest={documentId,baseRevisionId,content:'one\nTWO\n',message:'non-overlapping',proposalId:'prop-bbbbbbbbbbbb',via:'panel'};
 assert.equal((await a.documentOperation('submitDocumentProposal',mergedRequest)).status,'clean');
 assert.equal((await a.documentOperation('submitDocumentProposal',mergedRequest)).status,'clean','merged retry retains original request identity');
 assert.equal((await a.documentOperation('getDocument',{documentId,via:'panel'})).document.content,'ONE\nTWO');
 const conflicted=await a.documentOperation('submitDocumentProposal',{documentId,baseRevisionId,content:'uno\ntwo',message:'overlap',proposalId:'prop-cccccccccccc',via:'panel'});
 assert.equal(conflicted.status,'conflict');
 const remoteConflict=await b.documentOperation('getDocument',{documentId,via:'panel'});
 assert.equal(remoteConflict.proposal.proposedContent,'uno\ntwo');
 await assert.rejects(a.documentOperation('resolveDocumentConflict',{documentId,proposalId:'prop-cccccccccccc',content:'agent override',via:'tool',sessionId:'agent'}),/agent|human/i);
 await a.documentOperation('resolveDocumentConflict',{documentId,proposalId:'prop-cccccccccccc',content:'resolved',message:'human solution',via:'panel'});
 await assert.rejects(a.documentOperation('confirmDocumentResolution',{documentId,proposalId:'prop-cccccccccccc',via:'panel'}),/maintainer|leader|confirm/i);
 assert.equal((await b.documentOperation('confirmDocumentResolution',{documentId,proposalId:'prop-cccccccccccc',via:'panel'})).status,'clean');
 const beforeOffline=await a.documentOperation('getDocument',{documentId,via:'panel'});
 a.resolvePeers=()=>[];
 const queued=await a.documentOperation('submitDocumentProposal',{documentId,baseRevisionId:beforeOffline.document.headRevisionId,content:'offline proposal',message:'saved offline',proposalId:'prop-dddddddddddd',via:'panel'});
 assert.equal(queued.status,'pending');
 await (await a.sharedDocumentService()).close();a.sharedDocumentsPromise=undefined;
 const reopened=await a.sharedDocumentService();
 assert.ok(Object.values(reopened.store.state().idempotency).some(record=>record.pendingProposal&&record.decision==='pending'));
 a.resolvePeers=()=>[{nodeId:'node-b',address:'127.0.0.1',httpPort:b.server.port}];
 await reopened.flush();
 assert.equal((await a.documentOperation('getDocument',{documentId,via:'panel'})).document.content,'offline proposal');
 a.server=new MeshServer({describe:()=>a.describe(),secret:()=> 'secret',trustedPeers:()=>[],onSharedDoc:e=>reopened.receive(e),onMessage:e=>a.receive(e)});await a.server.listen(0);
 b.resolvePeers=()=>[{nodeId:'node-a',address:'127.0.0.1',httpPort:a.server.port}];
 await leader.flush();
 assert.ok(Object.values(leader.store.state().outbox).every(record=>record.status==='sent'));
 assert.equal(prompts.length,1,'replica sync never wakes Agents');
 assert.equal((await a.contextDeliveryStore().list())[0].packet.selectedDocumentVersions[0].content,'one\ntwo','later head changes preserve old delivery evidence');
 const remotePrompts=[];
 Object.defineProperty(b,'agents',{value:{get:id=>id==='worker'?{id,followup:prompt=>remotePrompts.push(prompt)}:undefined,list:()=>[{id:'worker'}]}});
 b.config.autoWake=true;
 const pinned={selectedDocumentVersions:[{documentId,revisionId:baseRevisionId,contentHash:read.document.contentHash}]};
 const remoteMessage=await a.sayInRoom({room:room.id,sessionId:'human',text:'Read old revision',mentions:[{memberKey:'node-b/worker',label:'Worker'}],contextSelection:pinned});
 assert.ok(remoteMessage.delivered.every(item=>item.ok));
 assert.equal(remotePrompts.length,1);
 assert.equal((await b.contextDeliveryStore().list())[0].packet.selectedDocumentVersions[0].revisionId,baseRevisionId);
 const taskCount=b.roomsDoc.rooms[room.id].tasks.length;
 await assert.rejects(b.assignTask({room:room.id,sessionId:'human',assignee:'node-a/agent',title:'invalid',contextSelection:{selectedDocumentVersions:[{documentId,revisionId:baseRevisionId,contentHash:'f'.repeat(64)}]}}),/mismatch/);
 assert.equal(b.roomsDoc.rooms[room.id].tasks.length,taskCount,'context validation happens before task creation');
 const task=await b.assignTask({room:room.id,sessionId:'human',assignee:'node-a/agent',title:'Read pinned design',contextSelection:pinned});
 assert.ok(task.delivered.every(item=>item.ok));
 assert.equal(prompts.length,2);
 assert.equal((await a.contextDeliveryStore().list()).at(-1).packet.taskId,task.task.id);
 const large='澄清'.repeat(12000);
 const big=await a.documentOperation('createDocument',{roomId:room.id,title:'Chunked history',content:large,via:'panel',requestId:'chunked-document'});
 assert.equal((await a.documentOperation('getDocument',{documentId:big.document.documentId,via:'panel'})).document.content,large,'authenticated snapshot chunks reconstruct full Unicode history');
 const fake=new MeshServer({describe:()=>({nodeId:'node-b',sharedDocs:1}),secret:()=> 'secret',trustedPeers:()=>[],onSharedDoc:e=>({body:{requestId:e.id,to:'node-a',from:'node-b',roomId:room.id,value:{status:'ready'}},sig:'0'.repeat(64)})});
 await fake.listen(0);t.after(()=>fake.close());
 a.resolvePeers=()=>[{nodeId:'node-b',address:'127.0.0.1',httpPort:fake.port}];
 await assert.rejects(a.documentOperation('getDocument',{documentId,via:'panel'}),/signature/);
 assert.equal((await a.sharedDocumentService()).store.state().documents[documentId].contentHash,leader.store.state().documents[documentId].contentHash,'bad signature does not alter persisted history');
});
